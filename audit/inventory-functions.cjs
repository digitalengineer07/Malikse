// Read-only syntax inventory. This is not a substitute for behavioral tests.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const ts = require('../server/node_modules/typescript');
const root = path.resolve(__dirname, '..');
const out = path.join(__dirname, 'production-2026-11-07');
fs.mkdirSync(out, { recursive: true });
const files = [...new Set(execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], { cwd: root, encoding: 'utf8' }).trim().split(/\r?\n/))]
  .filter(f => /\.(?:[cm]?js|tsx?)$/.test(f) && !/\.d\.ts$/.test(f) && !/\/dist[^/]*\//.test(f));
const functions = [], modules = [], routes = [];
for (const file of files) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) continue;
  const source = fs.readFileSync(full, 'utf8');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, file.endsWith('.tsx') ? ts.ScriptKind.TSX : /\.[cm]?js$/.test(file) ? ts.ScriptKind.JS : ts.ScriptKind.TS);
  const startCount = functions.length;
  function walk(node) {
    if ((ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node) || ts.isArrowFunction(node) || ts.isMethodDeclaration(node) || ts.isConstructorDeclaration(node) || ts.isGetAccessorDeclaration(node) || ts.isSetAccessorDeclaration(node)) && node.body) {
      const line = ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1;
      const end = ast.getLineAndCharacterOfPosition(node.end).line + 1;
      let name = node.name?.getText(ast);
      if (!name && (ts.isVariableDeclaration(node.parent) || ts.isPropertyAssignment(node.parent))) name = node.parent.name.getText(ast);
      if (!name && ts.isCallExpression(node.parent)) name = `${node.parent.expression.getText(ast)} callback`;
      const body = node.body.getText(ast);
      const flags = [];
      if (/\b(?:find|findOne|findById|aggregate|updateOne|updateMany|save|create|insertMany|deleteOne|deleteMany)\s*\(/.test(body)) flags.push('database');
      if (/\b(?:fetch|axios)\b/.test(body)) flags.push('network');
      if (/\b(?:localStorage|SecureStore|AsyncStorage)\b/.test(body)) flags.push('storage');
      if (/innerHTML|injectJavaScript|eval\(/.test(body)) flags.push('HTML/script sink');
      if (/setInterval|setTimeout/.test(body)) flags.push('timer');
      functions.push({ file, line, end, name: name || `<anonymous@${line}>`, flags, assessment: 'Syntax inventory; module review and test evidence in main report; no individual pass implied' });
    }
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && /^(get|post|put|patch|delete|head|options)$/.test(node.expression.name.text) && node.arguments[0] && ts.isStringLiteral(node.arguments[0]) && file.startsWith('server/src/')) {
      routes.push({ file, line: ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1, method: node.expression.name.text.toUpperCase(), path: node.arguments[0].text });
    }
    ts.forEachChild(node, walk);
  }
  walk(ast);
  modules.push({ file, lines: source.split(/\r?\n/).length, functions: functions.length - startCount });
}
fs.writeFileSync(path.join(out, 'function-inventory.json'), JSON.stringify({ scope: 'Current Git index plus nonignored untracked source; excludes generated bundles, declarations and local-only utilities', modules, functions, routes }, null, 2) + '\n');
const escape = value => String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
fs.writeFileSync(path.join(out, 'FUNCTION_INVENTORY.md'), '# Function and route inventory\n\nGenerated by `node audit/inventory-functions.cjs`. Every syntax-level function body, including nested callbacks, is listed. Generated bundles, declarations and ignored local utilities are excluded. This is coverage accounting, **not a claim that each function has been behaviorally verified**. See the main audit for findings and test limitations.\n\n' + `${modules.length} source files; ${functions.length} function bodies; ${routes.length} literal HTTP route registrations (dynamic registrations also exist).\n\n` + '| File:line | Function | Signals requiring review |\n|---|---|---|\n' + functions.map(f => `| ${escape(f.file)}:${f.line} | ${escape(f.name)} | ${f.flags.join(', ') || '—'} |`).join('\n') + '\n\n## HTTP registrations\n\n| File:line | Method | Local route |\n|---|---|---|\n' + routes.map(r => `| ${r.file}:${r.line} | ${r.method} | ${r.path} |`).join('\n') + '\n');
console.log(JSON.stringify({ files: modules.length, functions: functions.length, literalRoutes: routes.length }));
