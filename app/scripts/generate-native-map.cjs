const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

// Serialize source at build time: Hermes bytecode cannot return function source.
const root = path.resolve(__dirname, '..');
const source = ts.transpileModule(fs.readFileSync(path.join(root, 'src/utils/regionBoundaryLayer.ts'), 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText;
const script = `(function(){const exports={};\n${source}\nreturn exports.addRegionBoundaries;})()`;
const output = '// Generated by scripts/generate-native-map.cjs. Edit regionBoundaryLayer.ts instead.\nexport const regionBoundaryScript = ' + JSON.stringify(script) + ';\n';
const target = path.join(root, 'src/utils/regionBoundaryScript.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fs.writeFileSync(target, output);
